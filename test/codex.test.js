"use strict";
const assert = require("assert");
const { parseEvents } = require("../lib/codex");
const { createManager } = require("../lib/codex-jobs");
const { buildDefaultStore } = require("../lib/default-store");
const { createDepartmentRun, startItem, submitItem } = require("../lib/department");
(async () => {
  assert.throws(() => parseEvents('{"type":"item.completed","item":{"type":"agent_message","text":"partial"}}'), /完整/);
  assert.throws(() => parseEvents('{"type":"turn.failed","error":{"message":"quota"}}'), /quota/);
  assert.equal(parseEvents('{"type":"item.completed","item":{"type":"agent_message","text":"成果"}}\n{"type":"turn.completed"}').text, "成果");
  let store = buildDefaultStore(), resolve;
  const run = createDepartmentRun(store, { goal: "拆解一个公开研究任务" });
  const readStore = () => structuredClone(store), writeStore = s => { store = structuredClone(s); };
  const manager = createManager({ readStore, writeStore, generate: () => new Promise(r => { resolve = r; }) });
  const job = manager.start({ runId: run.id, role: "director" });
  assert.equal(manager.start({ runId: run.id, role: "director" }).id, job.id, "重复提交必须复用任务");
  await new Promise(r => setImmediate(r));
  store.events.unshift({ id: "concurrent", text: "同时发生的其他进度" });
  resolve({ text: "子任务和验收标准", threadId: "test" });
  await new Promise(r => setImmediate(r));
  assert.equal(store.departmentRuns[0].items[0].output, "子任务和验收标准");
  assert(store.events.some(e => e.id === "concurrent"), "不得覆盖并发台账更新");
  assert.equal(store.codexJobs[0].status, "done");
  const run2 = createDepartmentRun(store, { goal: "失败恢复" });
  const failed = createManager({ readStore, writeStore, generate: async () => { throw new Error("额度不足"); } });
  failed.start({ runId: run2.id, role: "director" });
  await new Promise(r => setImmediate(r));
  assert.equal(store.codexJobs[0].status, "failed");
  assert.equal(store.departmentRuns[0].items[0].status, "queued");
  const interrupted = failed.start({ runId: run2.id, role: "director" });
  failed.recover();
  assert.equal(store.codexJobs.find(j => j.id === interrupted.id).status, "failed");
  await new Promise(r => setImmediate(r));
  const reviewRun = store.departmentRuns.find(r => r.id === run.id);
  reviewRun.items[1].ownerAgentId = "workbuddy";
  startItem(store, run.id, reviewRun.items[1].id);
  submitItem(store, run.id, reviewRun.items[1].id, { output: "缺少证据的初稿" });
  const reviewer = createManager({ readStore, writeStore, generate: async () => ({ text: "缺少证据。VERDICT: REJECT" }) });
  reviewer.start({ runId: run.id, role: "reviewer" });
  await new Promise(r => setImmediate(r));
  assert.equal(store.departmentRuns.find(r => r.id === run.id).items[1].status, "rework");
  console.log("Codex event, deduplication, persistence and failure recovery checks passed.");
})().catch(e => { console.error(e); process.exitCode = 1; });
