const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'bench-archive-api-'));
process.env.BENCH_DATA_DIR=root;
const {buildDefaultStore}=require('../lib/default-store');
const state=buildDefaultStore();
state.tasks=[{id:'test-task',title:'中文原文不翻译',status:'doing',progress:41}];
state.fronts={};state.fronts.learn=[{id:'front-current',title:'Keep current',progress:12},{id:'front-archived',title:'Keep archive',archived:true,progress:23}];
state.modules=[{id:'test-module',title:'测试模块',taskId:'test-task'}];
fs.writeFileSync(path.join(root,'store.json'),JSON.stringify(state));
const {createServer}=require('../server');
const server=createServer();
(async()=>{
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base='http://127.0.0.1:'+server.address().port;
  const request=async(route,body,method='POST')=>fetch(base+route,{method,headers:{'Content-Type':'application/json'},body:body&&JSON.stringify(body)});
  const archive={action:'archive',items:[{collection:'modules',id:'test-module'}]};
  const preview=await request('/api/archive/preview',archive);assert.equal(preview.status,200);assert.equal((await preview.json()).count,2);
  assert(!JSON.parse(fs.readFileSync(path.join(root,'store.json'))).tasks[0].archived);
  assert.equal((await request('/api/archive',archive)).status,200);
  assert.equal((await request('/api/checkpoint',{taskId:'test-task',status:'done'})).status,409);
  assert.equal((await request('/api/tasks/test-task',{archived:false},'PATCH')).status,400);
  assert.equal((await request('/api/archive',{...archive,action:'restore'})).status,200);
  assert.equal((await request('/api/checkpoint',{taskId:'test-task',status:'done'})).status,409);
  assert.equal((await request('/api/archive',{...archive,action:'resume'})).status,200);
  assert.equal((await request('/api/meta',{language:'en'},'PATCH')).status,200);
  assert.equal((await request('/api/meta',{language:'xx'},'PATCH')).status,400);
  assert.equal((await request('/api/fronts',{learn:[{id:'front-current',title:'Keep current',progress:44}]},'PATCH')).status,200);
  assert.equal((await request('/api/fronts',{learn:[{id:'front-archived',title:'Forbidden edit',progress:100}]},'PATCH')).status,409);
  const current=await (await request('/api/state',undefined,'GET')).json();
  assert.equal(current.fronts.learn.length,2);assert.equal(current.fronts.learn.find(row=>row.id==='front-archived').progress,23);
  assert.equal(current.meta.language,'en');assert.equal(current.tasks[0].title,'中文原文不翻译');assert.equal(current.tasks[0].progress,41);
  const doc=await (await request('/api/help/logic?language=en',undefined,'GET')).text();assert.match(doc,/Type 1 workbench/);assert.match(doc,/```mermaid/);
  assert.equal((await request('/api/help/logic?language=../../store.json',undefined,'GET')).status,200);
  console.log('Archive API persistence, preview, paused write protection, language validation and whitelisted guide routes passed with an isolated ledger.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>server.close());
