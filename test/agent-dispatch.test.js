"use strict";
const assert = require("assert");
const { buildDefaultStore } = require("../lib/default-store");
const dept = require("../lib/department");
const dispatch = require("../lib/agent-dispatch");
const store = buildDefaultStore();
const run = dept.createDepartmentRun(store, { goal: "验证真实领取与审核依赖", participantAgentIds: ["codex", "cursor", "workbuddy"] });
const director = dept.getItem(run,"director"), executor = dept.getItem(run,"executor"), reviewer = dept.getItem(run,"reviewer");
executor.ownerAgentId = "workbuddy"; reviewer.ownerAgentId = "cursor";
assert.equal(dispatch.syncAssignments(store), false);
dept.startItem(store, run.id, director.id);
dept.submitItem(store, run.id, director.id, { output: "先核验材料，形成纲要" });
assert.ok(dispatch.syncAssignments(store));
assert.equal(dispatch.syncAssignments(store), false);
assert.equal(dispatch.claim(store, { agentId:"cursor", runId:run.id }), null);
assert.ok(dispatch.claim(store, { agentId:"workbuddy", runId:run.id }));
assert.equal(executor.status,"doing");
assert.equal(dispatch.claim(store, { agentId:"workbuddy", runId:run.id }), null);
dept.submitItem(store, run.id, executor.id, { output:"可核验成果" });
dispatch.syncAssignments(store);
assert.ok(dispatch.claim(store, { agentId:"cursor", runId:run.id }));
dept.reviewExecutor(store,run.id,{reviewerAgentId:"cursor",verdict:"reject",comment:"补充证据"});
dispatch.syncAssignments(store);
assert.ok(dispatch.claim(store,{agentId:"workbuddy",runId:run.id}));
assert.equal(executor.attempts,2,"返工领取也必须累计次数，以便阻止无限返工");
assert.equal(executor.status,"rework");
dept.completeRework(store,run.id,executor.id,{output:"已补证据"});
dispatch.syncAssignments(store);
assert.ok(dispatch.claim(store,{agentId:"cursor",runId:run.id}));
run.archived=true;
assert.throws(()=>dispatch.claim(store,{agentId:"cursor",runId:run.id}), /archived/);
console.log("Agent dispatch dependency, deduplication, claim and rework checks passed");
