'use strict';
const assert = require('node:assert/strict');
const g = require('../lib/growth');
const store = { tasks: [{ id: 'task-1', title: '既有任务', progress: 38 }], agendas: [{ id: 'agenda-1', title: '既有行程', done: false }] };
const original = JSON.stringify(store);
assert.equal(g.snapshot(store).plan, null); assert.equal(JSON.stringify(store), original, '只读快照不得初始化台账');
assert.equal(g.BLOCKS.reduce((n, b) => n + b.minutes, 0), 300);
assert.throws(() => g.activate(store, { startDate: '2026-02-30' }), /日期不存在/);
const plan = g.activate(store, { startDate: '2026-11-09' }, '2026-11-09T00:00:00Z');
assert.equal(plan.sessions.length, 40); assert.equal(plan.deadline, '2027-01-03');
assert.equal(new Set(plan.sessions.map(s => s.id)).size, 40);
assert.equal(g.activate(store, { startDate: '2026-11-10' }).id, plan.id); assert.equal(store.lifeSystem.learningPlans.length, 1);
assert.throws(() => g.setSession(store, plan.sessions[0].id, { expectedRevision: 0, done: true }), /记录已变化/);
assert.throws(() => g.setSession(store, plan.sessions[0].id, { expectedRevision: 1, done: 'true' }), /布尔/);
for (const session of plan.sessions) g.setSession(store, session.id, { expectedRevision: plan.revision, done: true });
assert.equal(plan.status, 'completed'); assert.equal(plan.sessions.length, 40, '完成后保留所有分次记录');
g.setSession(store, plan.sessions[0].id, { expectedRevision: plan.revision, done: false });
assert.equal(plan.status, 'active'); assert.equal(plan.completedAt, undefined);
const input = { requestId: 'test-request-001', kind: 'case', title: '材料价差案例', body: '教学情景，尚待核实。', week: 1, mastery: 2, evidence: '能够识别合同约定和证据缺口。', sourceTitle: '公开学习资料', sourceUrl: 'https://example.com/source', sourceVersion: 'v1', locator: '第1页', sourceStatus: 'entry', relatedTaskId: 'task-1', relatedAgendaId: 'agenda-1' };
const first = g.saveCard(store, null, input, '2026-11-09T01:00:00Z');
assert.equal(g.saveCard(store, null, input).id, first.id); assert.equal(store.lifeSystem.growthCards.length, 1);
assert.throws(() => g.saveCard(store, first.id, { ...input, expectedRevision: 0 }), /记录已变化/);
assert.throws(() => g.saveCard(store, null, { ...input, requestId: 'invalid-source-1', sourceUrl: 'javascript:alert(1)' }), /HTTP/);
assert.throws(() => g.saveCard(store, null, { ...input, requestId: 'invalid-review-1', mastery: 3 }), /专业复核/);
assert.throws(() => g.saveCard(store, null, { ...input, requestId: 'invalid-proof-1', evidence: '' }), /理解证据/);
assert.throws(() => g.saveCard(store, null, { ...input, requestId: 'invalid-link-1', relatedTaskId: 'missing' }), /关联任务/);
const reviewed = g.saveCard(store, first.id, { ...input, expectedRevision: 1, mastery: 3, reviewer: '测试核对人', reviewNote: '已核对本教学情景与分析。', reviewConfirmed: true }, '2026-11-09T02:00:00Z');
assert.equal(reviewed.mastery, 3); assert.equal(reviewed.history.length, 1);
const changed = g.saveCard(store, first.id, { ...reviewed, expectedRevision: 2, body: '调整了关键条件。', reviewConfirmed: true }, '2026-11-09T03:00:00Z');
assert.equal(changed.mastery, 2); assert.equal(changed.reviewer, ''); assert.equal(changed.reviewInvalidated, true);
assert.equal(changed.history[1].mastery, 3); assert.equal(changed.history[1].reviewer, '测试核对人');
const beforeDraft = JSON.stringify(store), summary = g.weeklyDraft(store, 1);
assert.match(summary.body, /不是实际投入时长或掌握证明/); assert.match(summary.body, /材料价差案例/); assert.match(summary.body, /待本人补充/);
assert.equal(JSON.stringify(store), beforeDraft, '生成周总结草稿不写台账');
g.archiveCard(store, first.id, { expectedRevision: 3, archived: true });
assert.equal(g.snapshot(store).cards[0].archived, true); assert.doesNotMatch(g.weeklyDraft(store, 1).body, /材料价差案例/);
g.archiveCard(store, first.id, { expectedRevision: 4, archived: false });
assert.equal(store.lifeSystem.growthCards[0].history.length, 4);
assert.equal(store.tasks[0].progress, 38); assert.equal(store.agendas[0].done, false, '卡片引用不改业务状态');
plan.archived = true;
assert.throws(() => g.setSession(store, plan.sessions[0].id, { expectedRevision: plan.revision, done: true }), /有效/);
assert.throws(() => g.activate(store, { startDate: '2026-11-09' }), /归档或暂停/);
console.log('V9 domain: read-only snapshot, 300-minute plan, idempotency, date validation, 40 retained sessions, reopening, evidence gates, review invalidation/history, conflicts, weekly draft, archive/restore and original record boundaries passed.');
