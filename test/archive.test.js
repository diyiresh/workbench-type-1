const assert=require('node:assert/strict');
const {changeArchive,inactive,migrateArchive,operationalStore}=require('../lib/archive');
const dept=require('../lib/department');
const {buildDefaultStore}=require('../lib/default-store');
const {dueImportantReminders}=require('../lib/agenda-reminders');
const {eligibleRequest}=require('../lib/workbuddy-queue');
const {createManager}=require('../lib/codex-jobs');
const {createRuntime}=require('../lib/external-runtime');
const next=()=>new Promise(resolve=>setImmediate(resolve));
(async()=>{
  let store=buildDefaultStore();
  store.tasks=[{id:'task',title:'原始业务标题',status:'doing',notes:'不得改变正文',ownerAgentId:'workbuddy'}];
  store.modules=[{id:'module',taskId:'task',title:'绑定模块'}];
  store.inbox=[{id:'instruction',relatedId:'task',status:'queued',body:'原始指令'}];
  const request={action:'archive',items:[{collection:'modules',id:'module'}]};
  const before=structuredClone(store);
  assert.equal(changeArchive(store,request,{preview:true}).count,3);
  assert.deepEqual(store,before,'Preview must not mutate records');
  assert.throws(()=>changeArchive(store,{...request,items:[...request.items,{collection:'tasks',id:'missing'}]}));
  assert.deepEqual(store,before,'Invalid batch must be atomic');
  changeArchive(store,request);
  assert.equal(store.tasks[0].status,'doing');assert.equal(store.tasks[0].notes,before.tasks[0].notes);
  assert.equal(operationalStore(store).tasks.length,0);
  changeArchive(store,{...request,action:'restore'});
  assert(!store.tasks[0].archived);assert(inactive(store.tasks[0]));
  changeArchive(store,{...request,action:'resume'});assert(!inactive(store.tasks[0]));
  assert.throws(()=>changeArchive(store,{action:'archive',items:[{collection:'agents',id:'workbuddy'}]}),/active_assignments/);
  const now=new Date('2026-10-12T00:00:00');
  assert.equal(dueImportantReminders([{date:'2026-10-12',time:'10:00',important:true,archived:true},{date:'2026-10-12',time:'10:00',important:true,resumeRequired:true}],now).length,0);
  const legacy={tasks:[{id:'legacy',status:'archive',progress:40}],meta:{}};migrateArchive(legacy);
  assert.equal(legacy.tasks[0].status,'todo');assert(legacy.tasks[0].archived);assert.equal(legacy.tasks[0].progress,40);
  const run=dept.createDepartmentRun(store,{goal:'Synthetic asynchronous check',participantAgentIds:['codex','workbuddy','cursor']});
  run.externalAutomation=true;run.automationPaused=true;
  const ref={collection:'departmentRuns',id:run.id};
  changeArchive(store,{action:'archive',items:[ref]});
  changeArchive(store,{action:'restore',items:[ref]});
  assert.throws(()=>dept.startItem(store,run.id,dept.getItem(run,'director').id),/paused_or_archived/);
  assert(!eligibleRequest(store,{runId:run.id,jobId:'any'}));
  changeArchive(store,{action:'resume',items:[ref]});assert(run.automationPaused,'A pre-existing review pause survives archive/restore/continue');
  run.automationPaused=false;
  let release;
  const readStore=()=>structuredClone(store),writeStore=fresh=>{store=structuredClone(fresh);};
  const manager=createManager({readStore,writeStore,generate:()=>new Promise(resolve=>{release=resolve;})});
  manager.start({runId:run.id,role:'director'});await next();
  changeArchive(store,{action:'archive',items:[ref]});
  changeArchive(store,{action:'restore',items:[ref]});
  changeArchive(store,{action:'resume',items:[ref]});
  release({text:'Late output must be retained',threadId:'synthetic'});await next();
  assert.equal(store.codexJobs[0].status,'held');assert.equal(store.codexJobs[0].output,'Late output must be retained');
  assert.equal(dept.getItem(dept.getRun(store,run.id),'executor').status,'blocked');
  const run2=dept.createDepartmentRun(store,{goal:'External late output',participantAgentIds:['codex','workbuddy','cursor']});
  run2.requiresWritingApproval=false;run2.externalAutomation=true;run2.workbuddyTransport='cli';
  dept.startItem(store,run2.id,dept.getItem(run2,'director').id);dept.submitItem(store,run2.id,dept.getItem(run2,'director').id,{output:'Plan'});
  const runtime=createRuntime({readStore,writeStore,execute:()=>new Promise(resolve=>{release=resolve;})});
  runtime.start(run2.id,dept.getItem(run2,'executor').id);await next();
  changeArchive(store,{action:'archive',items:[{collection:'departmentRuns',id:run2.id}]});
  release('External result retained');await next();
  assert.equal(store.externalJobs[0].status,'held');assert.equal(store.externalJobs[0].output,'External result retained');
  assert.equal(dept.getItem(dept.getRun(store,run2.id),'reviewer').status,'blocked');
  // A preparation review returning after archive is retained without starting integration.
  const preparation=require('../lib/preparation-flow').createPreparationFlow;
  const run3=dept.createDepartmentRun(store,{goal:'Preparation late review',participantAgentIds:['codex','workbuddy','cursor']});
  run3.externalAutomation=true;const prepExecutor=dept.getItem(run3,'executor');prepExecutor.preparationReady=true;prepExecutor.output='Source outline';
  let integrations=0;
  const prep=preparation({readStore,writeStore,review:()=>new Promise(resolve=>{release=resolve;}),summarize:()=>{integrations++;return {text:'Must not happen'};}});
  prep.tick();await next();changeArchive(store,{action:'archive',items:[{collection:'departmentRuns',id:run3.id}]});
  release('Original late review');await next();await next();
  assert.equal(integrations,0);assert.equal(dept.getRun(store,run3.id).preparationLateResults[0].output,'Original late review');
  assert.equal(dept.getRun(store,run3.id).preparationFlow.status,'held');
  assert.throws(()=>runtime.start(run3.id,prepExecutor.id),/paused_or_archived/);
  console.log('Archive dependency preview, atomicity, restoration pause, reminders, queue exclusion, legacy migration and late-result retention passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
